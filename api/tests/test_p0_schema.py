def test_migration_roundtrip_and_models_match(scratch_url):
    cfg = alembic_config(scratch_url)
    reset_schema(scratch_url)
    command.upgrade(cfg, "head")
    command.downgrade(cfg, "base")
    command.upgrade(cfg, "head")
    try:
        command.check(cfg)
    except AutogenerateDiffsDetected as exc:  # pragma: no cover - 실패 메시지용
        pytest.fail(f"모델과 마이그레이션이 다르다: {exc}")
